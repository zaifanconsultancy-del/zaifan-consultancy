export function findItalianUniversityBySlug(slug) {
  return italianUniversities.find((university) => university.slug === slug);
}

export function getTopItalianUniversities(limit = 3) {
  return italianUniversities.slice(0, limit);
}

export function getTuitionBadge(level) {
  if (level === "Premium") return "Premium Route";
  if (level === "Moderate") return "Balanced Cost";
  return "Budget Friendly";
}

export function getScholarshipBadge(strength) {
  if (strength === "Excellent") return "Strong Scholarships";
  if (strength === "Selective") return "Selective Awards";
  return "Scholarships Available";
}

